package com.moda.mobile.ui.components

import androidx.compose.ui.unit.dp

/**
 * 宽屏上需要单独封顶的两处尺寸。
 *
 * 界面整体已经按"手机一套布局"定死（竖屏锁定，清单里锁的 portrait），所以页面本身不做
 * 宽度分档，也没有居中的内容列；剩下会跟着窗口无限变宽的只有两类浮层：
 *
 *  - 播放器底部面板：播放页是全应用唯一会横过来的页面，平板上窗口宽 1280dp，
 *    面板铺满整条会宽得不成比例；
 *  - 自绘弹窗：Dialog 的默认窗口宽度按屏幕比例给，平板上会撑成一整片。
 *
 * 两个数只在这两个地方用，改之前先看调用点上的说明。
 */

/**
 * 播放器底部面板（倍速 / 选集 / 更多…）在宽屏上的最大宽度。
 *
 * 手机横屏一般窄于 840dp，取值等于"没有上限"，七个面板依旧一样宽；
 * 平板上收在中间，每一行的长度才跟手机接近。
 */
val PlayerSheetMaxWidth = 840.dp

/**
 * 自绘弹窗（更新 / 版权 / 存储引导）的最大宽度。
 *
 * 这三张弹窗都是 `Dialog { Column(fillMaxWidth) }`，Dialog 的默认窗口宽度按屏幕比例给，
 * 平板上会撑成一整片。Material3 的 AlertDialog 自带 560dp 上限，这三张没有，所以在这里补一个。
 */
val DialogMaxWidth = 420.dp
